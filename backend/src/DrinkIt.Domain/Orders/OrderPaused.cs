namespace DrinkIt.Domain.Orders;

public sealed record OrderPaused : IOrderChanged
{
    public OrderPaused(Guid venueId, TrackingToken trackingToken)
    {
        VenueId = venueId;
        TrackingToken = trackingToken;
    }

    public Guid VenueId { get; }

    public TrackingToken TrackingToken { get; }
}
